const STOP = new Set(["the", "and", "for", "with", "from", "that", "this", "near", "me"]);

export function vehicleTitle(vehicle: RetailVehicle) {
  return `${vehicle.year} ${vehicle.make} ${vehicle.model}`;
}

export function matchLinders(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return LINDERS;
  const tokens = q.split(/[^a-z0-9]+/).filter((token) => token.length > 1 && !STOP.has(token));
  if (!tokens.length) return [];
  return LINDERS.filter((vehicle) => {
    const hay = norm(
      [vehicle.year, vehicle.make, vehicle.model, vehicle.trim, vehicle.exterior, vehicle.interior, vehicle.stock, vehicle.engine, vehicle.drivetrain, vehicle.style, vehicle.vin]
        .filter(Boolean)
        .join(" "),
    );
    return tokens.every((token) => hay.includes(norm(token)));
  });
}

