export function categoryLabel(id: CategoryId) {
  return CATEGORIES.find((c) => c.id === id)?.label ?? id;
}

export function photoFor(id: CategoryId) {
  return CATEGORIES.find((c) => c.id === id)?.photo ?? "/photos/yard.jpg";
}

export function partCategory(part: string): CategoryId {
  return PARTS.find((p) => p.part === part)?.category ?? "body";
}

function warrantyFor(sellerType: "yard" | "private", condition: Condition) {
  if (sellerType === "private") return "Private sale. Meet in a public lot. No warranty unless the seller wrote one.";
  if (condition === "As-is") return "As-is pull. Look it over before you leave. No comeback.";
  if (condition === "Tested") return "Tested on the bench or on the donor. 30 days if you keep the tag.";
  if (condition === "Rebuilt") return "Rebuilt unit. Ask what was replaced before you hand over cash.";
  return "New takeoff. Taken off, never run on the road.";
}

type Seed = {
  id: string;
  part: string;
  category: CategoryId;
  yearStart: number;
  yearEnd: number;
  make: string;
  model: string;
  condition: Condition;
  price: number;
  floor: number;
  city: string;
  miles: number;
  sellerName: string;
  sellerType: "yard" | "private";
  yardName?: string;
  bin?: string;
  donorMiles?: string;
  engineNote: string;
  description: string;
  aliases?: string[];
  hoursAgo: number;
  acceptsOffers?: boolean;
  pulled?: boolean;
};

function listing(s: Seed): Listing {
  return {
    id: s.id,
    title: `${yearsLabel(s.yearStart, s.yearEnd)} ${s.make} ${s.model} ${s.part}`,
    part: s.part,
    category: s.category,
    yearStart: s.yearStart,
    yearEnd: s.yearEnd,
    make: s.make,
    model: s.model,
    engineNote: s.engineNote,
    aliases: s.aliases ?? [],
    condition: s.condition,
    price: s.price,
    floor: s.floor,
    acceptsOffers: s.acceptsOffers ?? true,
    city: s.city,
    miles: s.miles,
    yardName: s.yardName,
    bin: s.bin,
    donorMiles: s.donorMiles,
    description: s.description,
    photo: photoFor(s.category),
    sellerName: s.sellerName,
    sellerType: s.sellerType,
    postedAt: BOARD_CLOCK - s.hoursAgo * 3600000,
    warranty: warrantyFor(s.sellerType, s.condition),
    status: "active",
    pulled: s.pulled,
  };
}

